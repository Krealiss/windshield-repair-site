-- Попередження, які стосуються самої заявки: «фото не передалося»,
-- «не вмістилося знімків: N».
--
-- Навіщо колонка. Картку перемальовує /api/tg із того, що є в базі.
-- Доки ці рядки жили лише в памʼяті запиту /api/lead, перший же натиск
-- кнопки стирав із картки єдину підказку «передзвоніть і попросіть
-- надіслати знімки» — причому саме тоді, коли оператор брав заявку в
-- роботу, тобто коли підказка потрібна найбільше.
--
-- Формат — готові рядки через \n, а не JSON: картка складається з
-- рядків, тож зберігати рівно те, що показується, дешевше за розбір, і
-- вміст видно очима в `d1 execute`. Майбутня CRM однаково рахуватиме
-- не текст, а окремі типізовані поля (чи дійшло фото, скільком
-- відмовили) — вона додасть їх міграцією, а не парситиме цей рядок.
--
-- SQLite не має ADD COLUMN IF NOT EXISTS. Якщо міграцію накотити
-- вдруге, ALTER впаде з «duplicate column name: notes» — це нешкідливо
-- й означає рівно те, що колонка вже на місці. `wrangler d1 migrations
-- apply` веде власну таблицю застосованого й другого разу не запустить.
ALTER TABLE leads ADD COLUMN notes TEXT;
