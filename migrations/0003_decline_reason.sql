-- Причина відмови: чому заявка не стала роботою.
--
-- Навіщо колонка. Сам стан «Відмова» відповідає на питання «що
-- сталося», але не на «чому». Для однієї заявки це дрібниця; на сотні
-- це єдина відповідь на питання, через що втрачаються клієнти — надто
-- дорого, тріщина вже не ремонтна чи просто не додзвонились. Без
-- окремої колонки таке доводиться згадувати або не рахувати зовсім.
--
-- Чому текст, а не номер причини. Готових причин чотири, і в кнопках
-- їде саме номер (REASONS у functions/_lib/card.ts), але в базі лежить
-- уже розгорнутий рядок. Причин дві: картку перемальовує /api/tg із
-- того, що є в базі, і зберігати рівно те, що показується, дешевше за
-- пошук по списку; а головне — є ще вільна причина, яку оператор пише
-- сам, і номера для неї не існує. Одна колонка на обидва випадки
-- замість номера плюс тексту.
--
-- Майбутня CRM рахуватиме відмови за типами, і їй знадобиться саме
-- номер. Тоді вона додасть колонку міграцією й розкладе накопичене —
-- це дешевше, ніж заводити другу колонку зараз під звітність, якої
-- ще немає.
--
-- Колонка порожня в усіх станах, крім відмови: «Повернути» її очищає,
-- бо повернення заявки означає, що відмова була помилкою.
--
-- SQLite не має ADD COLUMN IF NOT EXISTS. Повторний прогін упаде з
-- «duplicate column name: decline_reason» — це нешкідливо й означає,
-- що колонка вже на місці. `wrangler d1 migrations apply` веде власну
-- таблицю застосованого й другого разу не запустить.
ALTER TABLE leads ADD COLUMN decline_reason TEXT;
