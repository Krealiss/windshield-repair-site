-- Ставка, за якою нараховано цей рядок журналу.
--
-- Навіщо. Доти відсоток жив однією константою в коді, і зміна 10 на 15
-- переписувала б уже назване людям число: журнал захищає свої рядки, але
-- не баланс — будь-яка наступна дія над старою закритою заявкою
-- перерахувала б її за новою ставкою й тихо доплатила різницю.
--
-- Рішення замовника: нова ставка діє лише на заявки, за які ще не
-- нараховували. Тому ставка стає властивістю заявки, а не поточного
-- стану коду: при першому нарахуванні вона лягає в рядок, і всі
-- подальші перерахунки цієї заявки (уточнення суми, повернення,
-- повторне закриття) рахуються за нею.
--
-- Типове значення 10 — те, за яким нараховано все до цієї міграції.
-- У бойовій базі таких рядків немає взагалі, але локальні стенди й
-- майбутній відкат на цю версію мають читатися однозначно.
ALTER TABLE cashback ADD COLUMN pct INTEGER NOT NULL DEFAULT 10;
