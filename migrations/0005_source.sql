-- Звідки прийшла заявка: із сайту чи телефонним дзвінком.
--
-- Навіщо колонка саме зараз, разом із заведенням заявки руками.
-- Телефонні звернення в такій майстерні, найімовірніше, становлять
-- більшу частину потоку. Щойно вони зʼявляться в базі поряд із
-- вебзаявками, перше ж питання власника буде «а скільки з них звідки» —
-- і без цієї колонки відповісти буде нічим, а добудовувати її
-- доведеться міграцією по живих даних, задним числом гадаючи, що було
-- чим.
--
-- Значення латиницею, як і стани: site | phone. База не має розбирати
-- українські написи.
--
-- Типове значення 'site' не випадкове: усі рядки, що існували до цієї
-- міграції, прийшли з форми на сайті — іншого шляху не було. SQLite при
-- ADD COLUMN із DEFAULT проставляє його і наявним рядкам, тож окремий
-- UPDATE не потрібен.
--
-- Воркер сайту (functions/api/lead.ts) цю колонку не згадує навмисно:
-- типове значення робить саме те, що треба, а не чіпати робочий код
-- заради одного слова — дешевше й безпечніше.
ALTER TABLE leads ADD COLUMN source TEXT NOT NULL DEFAULT 'site';

-- Звіт «звідки клієнти» питатиме саме це
CREATE INDEX IF NOT EXISTS idx_leads_source ON leads (source);
