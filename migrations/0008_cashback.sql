-- Журнал кешбеку: нарахування на номер телефона.
--
-- Навіщо журнал, а не колонка з балансом. Число, яке зберігають окремо
-- від подій, що його склали, рано чи пізно розходиться з ними — і тоді
-- вже ніхто не скаже, яке з двох правильне. Тут баланс не зберігається
-- ніде: це `SUM(kop)` за номером, тож він завжди дорівнює тому, що
-- записано. Рядок журналу ніколи не редагується й не видаляється:
-- виправлення — це новий рядок, відʼємне `kop` (сторно). Тому в картці
-- клієнта видно, що сталося, а зміна відсотка через пів року не
-- переписує те, що людині вже пообіцяли.
--
-- `kop` — копійки, як і `leads.amount`. `lead_id` — за яку заявку
-- нараховано; сума `kop` за заявкою — це те, що їй уже записано, і
-- правило синхронізації (shared/cashback.ts) дописує різницю між цим і
-- тим, що належить зараз. `phone` — той самий ключ, що в картці клієнта.
--
-- Бекфілу немає навмисно: на момент запуску в базі немає жодної
-- закритої заявки, тож нараховувати нема за що.
CREATE TABLE IF NOT EXISTS cashback (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  phone      TEXT    NOT NULL,
  lead_id    INTEGER NOT NULL,
  kop        INTEGER NOT NULL,
  created_at TEXT    NOT NULL
);

-- Баланс і журнал питають за номером; синхронізація — за заявкою
CREATE INDEX IF NOT EXISTS idx_cashback_phone ON cashback (phone);
CREATE INDEX IF NOT EXISTS idx_cashback_lead ON cashback (lead_id);
