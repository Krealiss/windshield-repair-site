-- Виконавець для рядків, яким міграція 0006 його не дала.
--
-- 0006 переносила assignee з actor один раз, а порядок розгортання —
-- спершу міграція, потім код. Кожне натискання «В роботу» у проміжку
-- давало заявку «в роботі» без виконавця, і 0006 її вже не наздогнала.
-- Саме це сталося з двома заявками власника.
--
-- Межа `status IN ('in_work','done')` навмисна: там, де заявку
-- відмовили, роботи не було, і той, хто натиснув «Відмова»,
-- виконавцем не є. Наявні відмовлені рядки не чіпаємо взагалі —
-- відрізнити виконавця, якого туди вписала 0006, від майстра, який
-- узяв заявку й сам же її відмовив, запитом неможливо.
UPDATE leads
   SET assignee_id = actor_id,
       assignee_name = actor_name
 WHERE assignee_id IS NULL
   AND actor_id IS NOT NULL
   AND actor_id <> ''
   AND status IN ('in_work', 'done');
