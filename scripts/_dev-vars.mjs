/**
 * Розбір .dev.vars — один на всіх, хто його читає.
 *
 * Тека скриптів невелика, але споживачів цього формату вже троє
 * (telegram-chat-id, telegram-webhook і все, що додасться). Копія
 * парсера в цьому проєкті вже розійшлася з оригіналом і принесла
 * дефект: один знімав лапки зі значення, другий — ні, і квотований
 * TELEGRAM_WEBHOOK_SECRET реєструвався в Telegram разом із лапками.
 * Виглядало це як «кнопки не працюють взагалі», бо кожен натиск
 * прилітав із секретом, який не збігався, і ендпоінт віддавав 403.
 *
 * Лапки знімаються навмисно: так робить сам wrangler, коли підхоплює
 * цей файл для pages dev. Скрипт мусить бачити те саме значення, що й
 * воркер, інакше вони розходяться тихо.
 *
 * Значення з цього файлу — секрети. Ніде не друкуємо їх, ані повністю,
 * ані частинами.
 */
import { readFileSync } from 'node:fs';

export const DEV_VARS = '.dev.vars';

/** KEY=VALUE у звичайний обʼєкт. Без залежностей: формат простіший за
    будь-яку бібліотеку, а зайва залежність у цьому проєкті заборонена. */
export function parseDevVars(text) {
  const env = {};
  for (const line of text.split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const i = t.indexOf('=');
    // Рядок без «=» — не пара, а сміття: раніше з нього виходив ключ
    // із самого рядка без останнього символу
    if (i === -1) continue;
    env[t.slice(0, i).trim()] = t
      .slice(i + 1)
      .trim()
      .replace(/^["']|["']$/g, '');
  }
  return env;
}

/**
 * Читає .dev.vars із кореня проєкту. Якщо файлу немає — кличе onMissing
 * (там скрипт сам вирішує, як помирати) і повертає порожній обʼєкт.
 */
export function readDevVars(onMissing) {
  let raw;
  try {
    raw = readFileSync(DEV_VARS, 'utf8');
  } catch {
    onMissing?.();
    return {};
  }
  return parseDevVars(raw);
}
